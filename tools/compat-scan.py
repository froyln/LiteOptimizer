#!/usr/bin/env python3
"""List every vanilla method the instance's other litemods mixin into.

Reads each litemod's mixin refmap (the MCP-named targets its mixins were compiled against, mapped
to Notch names) and ForgeGradle's notch-mcp.srg, and prints one row per (mod, vanilla class,
member). Two kinds: `member` = a method/field of the target the mixin injects into or shadows,
`call` = an invocation the mixin redirects/injects at (a `Lclass;method(desc)` key). Any vanilla
method this mod overwrites must be checked against this list: docs/compat/instance-mixins.md.

Usage: python3 tools/compat-scan.py > docs/compat/instance-mixins.md
"""
import glob, io, json, os, pathlib, re, sys, zipfile

INSTANCE = os.path.expanduser("~/.local/share/PrismLauncher/instances/1.12.2 test ai/minecraft/mods/1.12.2")
SRG = glob.glob(os.path.expanduser("~/.gradle/caches/minecraft/de/oceanlabs/mcp/mcp_stable/39/1.12.2/srgs/notch-mcp.srg"))[0]

classes, methods, fields = {}, {}, {}
for line in open(SRG):
    p = line.split()
    if p[0] == "CL:":
        classes[p[1]] = p[2]
    elif p[0] == "MD:":
        methods[(p[1], p[2])] = p[3]           # notch owner/name, desc -> mcp owner/name
    elif p[0] == "FD:":
        fields[p[1]] = p[2]

def mcp_class(notch):
    return classes.get(notch, notch)

def decode(value):
    """'Lawj;a(Lamu;...)V' -> ('net/minecraft/block/BlockPistonBase', 'onBlockPlacedBy', desc)"""
    m = re.match(r"L([^;]+);([^(:]+)(\(.*)?$", value)
    if not m:
        return (mcp_class(value.strip("L;")), "?", "")
    owner, name, desc = m.group(1), m.group(2), m.group(3) or ""
    if desc:
        full = methods.get((owner + "/" + name, desc))
        if full:
            return (full.rsplit("/", 1)[0], full.rsplit("/", 1)[1], desc)
    else:
        full = fields.get(owner + "/" + name)
        if full:
            return (full.rsplit("/", 1)[0], full.rsplit("/", 1)[1], "")
    return (mcp_class(owner), name, desc)

rows = []
for jar in sorted(glob.glob(os.path.join(INSTANCE, "*.litemod")) + glob.glob(os.path.join(INSTANCE, "*.jar"))):
    if os.path.basename(jar).startswith("liteoptimizer-"):
        continue
    z = zipfile.ZipFile(jar)
    names = z.namelist()
    refmaps = [n for n in names if n.endswith(".refmap.json")]
    mod = os.path.basename(jar)
    for rm in refmaps:
        data = json.load(io.TextIOWrapper(z.open(rm), "utf-8"))
        for mixin_cls, mapping in data.get("mappings", {}).items():
            for key, value in mapping.items():
                kind = "call" if key.startswith("L") else "member"
                owner, name, desc = decode(value)
                if not owner.startswith("net/minecraft"):
                    continue
                rows.append((owner.replace("/", "."), name, kind, mod, mixin_cls.rsplit("/", 1)[1]))

rows.sort()
print("# Vanilla members touched by the instance's other litemods\n")
print(f"Generated by `tools/compat-scan.py` from `{INSTANCE}`. `member` = method/field the mixin injects into,")
print("overwrites or shadows; `call` = an invocation inside some method that the mixin redirects or injects at.\n")
print("| vanilla class | member | kind | mod | mixin class |")
print("|---|---|---|---|---|")
for owner, name, kind, mod, cls in rows:
    print(f"| `{owner}` | `{name}` | {kind} | {mod} | `{cls}` |")
print(f"\n{len(rows)} rows, {len(set(r[0] for r in rows))} vanilla classes, {len(set(r[3] for r in rows))} mods.")
